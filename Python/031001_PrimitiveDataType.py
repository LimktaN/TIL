# 1. Primitive Data Types in Python
profile_number = 2030
print(profile_number)

print("")

# 2. Floating-point number
score = float(59.5)
print(score)

print("")

# 3. Boolean value
is_correct = True
print(is_correct)

print("")

# 4. String
teacher_name = "LIM"
print(teacher_name)

course_name = 'CSC'
print(course_name)

lecture_name = """
LIM
JIN
"""
print(lecture_name)

print("")

# 5. String indexing
print(teacher_name[0])
print(teacher_name[1])
print(teacher_name[2])

print("")

print(course_name[len(course_name) - 1])

print("")

# 6. String slicing
print(type(profile_number))
print(type(score))
print(type(is_correct))
print(type(lecture_name))