# Conditional Expression (Ternary Operator)
if 10 > 20:
    print(True)
else:
    print(False)

# 1. 사용자로부터 키를 입력 받아서 조건에 맞는 결과값 출력하기
if int(input("How tall are you? ")) > 180:
    print("You are tall.")
else:
    print("You are not tall.")

