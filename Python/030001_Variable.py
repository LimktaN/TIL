# 1. 사용자로부터 입력 받아 변수에 넣고 변수와 함께 출력하기
name = input("What is your name? ")
print("Here is my name, " + name)

print("")

# 2. 변수에 값을 할당하고 출력하기
name = "Lim"
print(name)

print("")

# 3. 여러 개의 변수를 한 줄에 할당하기
x, y = 10, 20
print("x:", x)
print("y:", y)

print("")

# 4. 여러 개의 변수를 같은 값으로 할당하기
x = y = 1
print("x:", x)
print("y:", y)

print("")

# 5. 숫자의 합을 출력하기
