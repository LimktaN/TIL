# 0. 문자열을 그대로 출력하기
print("Hello, World!")

print("")

# 1. 문자열 사이에 공백을 넣어서 출력하기
print("Hello" + "           " + "World!")

print("")

# 2. 문자열 사이에 쉼표를 넣어서 출력하기
print({'name': 'Lim', 'age': 30, 'city': 'Seoul'})

print("")

# 3. 리스트를 그대로 출력하기
print([1, 2, 3, 4, 5])

print("")

# 4. 숫자와 불리언을 그대로 출력하기
print(42)
print(3.14)
print(False)

print("")

# 5. 문자열 사이에 구분자 넣어서 출력하기
print('home', 'user', 'documents', sep='/')

print("")